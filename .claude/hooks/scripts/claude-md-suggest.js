// plugins/vivastack-core/hooks/scripts/claude-md-suggest.js
//
// Stop hook: scan the just-finished session's transcript for signals worth
// proposing as CLAUDE.md updates (user corrections, persistent rules, repeated
// bash workflows). Write a draft suggestion file under sessions/ — never block,
// never edit CLAUDE.md directly. The next SessionStart surfaces the pointer
// via additionalContext so the user reviews it while memory is fresh.

'use strict';
const fs = require('fs');
const path = require('path');
const { statePath, atomicWrite } = require('../lib/state');

const START_MARKER = '<!-- VCW:CLAUDE-MD-SUGGEST:START -->';
const END_MARKER = '<!-- VCW:CLAUDE-MD-SUGGEST:END -->';

// Phrases that indicate the user is asserting a persistent rule or correcting
// behavior. Matched case-insensitively against user message content.
const PERSISTENT_RULE_PATTERNS = [
  /from now on\b/i,
  /always\b/i,
  /never\b/i,
  /each time\b/i,
  /whenever\b/i,
  /every time\b/i,
];

const CORRECTION_PATTERNS = [
  /^no[,!.\s]/i,
  /you should\b/i,
  /you must\b/i,
  /don'?t\b/i,
  /stop\b/i,
  /wrong\b/i,
  /incorrect\b/i,
  /instead\b/i,
];

// A bash command repeated this many times in one session is probably worth
// documenting as a project workflow.
const REPEATED_BASH_THRESHOLD = 3;

const MAX_SIGNAL_LEN = 240;

function truncate(s, n = MAX_SIGNAL_LEN) {
  if (typeof s !== 'string') return '';
  const trimmed = s.trim().replace(/\s+/g, ' ');
  return trimmed.length > n ? trimmed.slice(0, n - 1) + '…' : trimmed;
}

function safeId(raw) {
  return String(raw || 'default').replace(/[^a-zA-Z0-9-]/g, '_').slice(0, 64);
}

function readTranscriptLines(transcriptPath) {
  if (!transcriptPath || !fs.existsSync(transcriptPath)) return [];
  return fs.readFileSync(transcriptPath, 'utf8').split('\n').filter(Boolean);
}

function classifyUserText(text) {
  const tags = [];
  for (const re of PERSISTENT_RULE_PATTERNS) {
    if (re.test(text)) { tags.push('rule'); break; }
  }
  for (const re of CORRECTION_PATTERNS) {
    if (re.test(text)) { tags.push('correction'); break; }
  }
  return tags;
}

function extractSignals(lines) {
  const corrections = [];
  const rules = [];
  const bashCounts = new Map();
  const seenSignals = new Set(); // dedupe identical text within a session

  for (const line of lines) {
    let entry;
    try { entry = JSON.parse(line); } catch { continue; }

    if (entry.type === 'user' && entry.message?.role === 'user') {
      const content = entry.message.content;
      const text = typeof content === 'string'
        ? content
        : Array.isArray(content)
          ? content.filter(b => b && typeof b.text === 'string').map(b => b.text).join(' ')
          : '';
      if (!text) continue;
      // skip command-stdout / hook injections that aren't real user speech
      if (/^<(local-command|command-name|command-message|command-args|local-command-stdout|local-command-caveat|system-reminder)/i.test(text.trim())) continue;
      const tags = classifyUserText(text);
      if (!tags.length) continue;
      const sig = truncate(text);
      const key = `${tags.join(',')}|${sig}`;
      if (seenSignals.has(key)) continue;
      seenSignals.add(key);
      if (tags.includes('rule')) rules.push(sig);
      else if (tags.includes('correction')) corrections.push(sig);
    }

    if (entry.type === 'assistant' && Array.isArray(entry.message?.content)) {
      for (const block of entry.message.content) {
        if (block.type === 'tool_use' && block.name === 'Bash') {
          const cmd = (block.input && typeof block.input.command === 'string') ? block.input.command.trim() : '';
          if (!cmd) continue;
          // collapse to a normalized form for counting
          const norm = cmd.replace(/\s+/g, ' ').slice(0, 240);
          bashCounts.set(norm, (bashCounts.get(norm) || 0) + 1);
        }
      }
    }
  }

  const repeatedBash = [...bashCounts.entries()]
    .filter(([, n]) => n >= REPEATED_BASH_THRESHOLD)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 10)
    .map(([cmd, n]) => ({ cmd, count: n }));

  return { corrections, rules, repeatedBash };
}

function hasAnySignals({ corrections, rules, repeatedBash }) {
  return corrections.length > 0 || rules.length > 0 || repeatedBash.length > 0;
}

function buildMarkdown({ corrections, rules, repeatedBash }, meta) {
  const { date, sessionId } = meta;
  const out = [];
  out.push('# CLAUDE.md update suggestions');
  out.push('');
  out.push(`> Generated by the Stop hook at the end of session \`${sessionId}\` on ${date}.`);
  out.push('> Review while the session is fresh; copy what is worth keeping into `CLAUDE.md` and delete this file.');
  out.push('');
  out.push(START_MARKER);

  if (rules.length) {
    out.push('## Persistent rules the user asserted');
    out.push('');
    for (const r of rules) out.push(`- ${r}`);
    out.push('');
  }

  if (corrections.length) {
    out.push('## Corrections worth encoding');
    out.push('');
    for (const c of corrections) out.push(`- ${c}`);
    out.push('');
  }

  if (repeatedBash.length) {
    out.push(`## Repeated bash commands (≥${REPEATED_BASH_THRESHOLD}× — candidate workflow notes)`);
    out.push('');
    for (const { cmd, count } of repeatedBash) {
      out.push(`- \`${cmd}\` — ${count}×`);
    }
    out.push('');
  }

  out.push(END_MARKER);
  out.push('');
  return out.join('\n');
}

async function run(input) {
  try {
    const transcriptPath = input?.transcript_path;
    const lines = readTranscriptLines(transcriptPath);
    if (lines.length === 0) return null;

    const signals = extractSignals(lines);
    if (!hasAnySignals(signals)) return null;

    const sessionId = safeId(input?.session_id);
    const date = new Date().toISOString().slice(0, 10);
    const filename = `${date}-${sessionId}-claude-md-suggest.md`;
    const outPath = statePath('sessions', filename);

    const md = buildMarkdown(signals, { date, sessionId });
    atomicWrite(outPath, md);

    process.stderr.write(`[VCW] CLAUDE.md update suggestions saved: ${outPath}\n`);
  } catch (err) {
    // never block on failure
    process.stderr.write(`[VCW] claude-md-suggest error: ${err.message}\n`);
  }
  return null;
}

module.exports = {
  run,
  // exported for tests
  PERSISTENT_RULE_PATTERNS,
  CORRECTION_PATTERNS,
  extractSignals,
  buildMarkdown,
  REPEATED_BASH_THRESHOLD,
};
